async function seed() {
  for (const [title, category, difficulty, trending] of TOPICS) {
    await query(
      `INSERT INTO topics(title, category, difficulty, trending) VALUES($1,$2,$3,$4) ON CONFLICT (title) DO NOTHING`,
      [title, category, difficulty, trending]
    );
  }

  // One-time import of accounts from the legacy data.json (passwords get hashed; stats are NOT imported
  // because they were hard-coded demo numbers, not real activity).
  const legacy = path.join(__dirname, "..", "data.json");
  if (fs.existsSync(legacy)) {
    try {
      const data = JSON.parse(fs.readFileSync(legacy, "utf8"));
      for (const u of data.users || []) {
        if (!config.seedDemo && u.email === "demo@debatepartner.ai") continue;
        const hash = await bcrypt.hash(String(u.password), 10);
        await query(
          `INSERT INTO users(name,email,password_hash) VALUES($1,$2,$3) ON CONFLICT (lower(email)) DO NOTHING`,
          [u.name, u.email, hash]
        );
      }
    } catch (e) {
      console.warn("[seed] could not import legacy data.json:", e.message);
    }
  }
}

